const locale = (lang: Lang) => (lang === 'th' ? 'th-TH' : 'en-GB');

export const fmtNum = (n: number, lang: Lang, digits = 0) =>
  n.toLocaleString(locale(lang), { minimumFractionDigits: digits, maximumFractionDigits: digits });

export const fmtBaht = (n: number, lang: Lang) => {
  const digits = Math.round(n) === n ? 0 : 2;
  return `฿${fmtNum(n, lang, digits)}`;
};

export const fmtCompactBaht = (n: number, lang: Lang) => {
  if (n >= 1e6) return `฿${fmtNum(n / 1e6, lang, n >= 1e7 ? 1 : 2)}M`;
  if (n >= 1e3) return `฿${fmtNum(n / 1e3, lang, n >= 1e5 ? 0 : 1)}K`;
  return `฿${fmtNum(n, lang)}`;
};

export const fmtDateTime = (t: number, lang: Lang) =>
  new Intl.DateTimeFormat(locale(lang), { timeZone: 'Asia/Bangkok', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }).format(t);

export const fmtDate = (t: number, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short' }) =>
  new Intl.DateTimeFormat(locale(lang), { timeZone: 'Asia/Bangkok', ...opts }).format(t);

/** Business-minute durations as "45 min", "3 h 10 min", "1.2 business days". */
export function fmtMinutes(min: number, lang: Lang): string {
  const m = Math.round(min);
  if (m < 60) return lang === 'th' ? `${m} นาที` : `${m} min`;
  const h = Math.floor(m / 60);
  const r = m % 60;
  if (lang === 'th') return r ? `${h} ชม. ${r} นาที` : `${h} ชม.`;
  return r ? `${h} h ${r} min` : `${h} h`;
}

export const fmtSize = (bytes: number) => (bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))}KB` : `${(bytes / 1024 / 1024).toFixed(2)}MB`);

