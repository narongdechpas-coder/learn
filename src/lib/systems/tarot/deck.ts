const pad = (n: number) => String(n).padStart(2, "0");

function makeCard(id: string, arcana: Arcana, suit: TarotSuit | null, number: number, e: Entry): TarotCard {
  const [nameEn, nameTh, keyword, upright, reversed] = e;
  return { id, nameEn, nameTh, arcana, suit, number, keyword, upright, reversed, image: `/tarot/${id}.webp` };
}

const SUIT_ORDER: TarotSuit[] = ["wands", "cups", "swords", "pentacles"];

export const TAROT_DECK: TarotCard[] = [
  ...MAJOR.map((e, i) => makeCard(`major-${pad(i)}`, "major", null, i, e)),
  ...SUIT_ORDER.flatMap((suit) => MINOR[suit].map((e, i) => makeCard(`${suit}-${pad(i + 1)}`, "minor", suit, i + 1, e))),
];
