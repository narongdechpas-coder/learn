/** สีประจำวันเกิดตามความเชื่อไทย */
const DAY_COLORS = ["", "แดง", "เหลือง", "ชมพู", "เขียว", "ส้ม", "ฟ้า", "ม่วง"];

const levelOf = (r: SevenResult, cols: number[]) =>
  sumLevel(Math.round(cols.reduce((s, c) => s + r.sums[c], 0) / cols.length));

/** สร้างคำทำนายแบบเล่าเรื่องจากผลคำนวณ (ไม่ใช้ AI) */
export function interpretSeven(r: SevenResult): Reading[] {
  const cell = (row: number, col: number) => r.rows[row][col].value;
  const day = r.isRahu ? "พุธกลางคืน" : DAY_NAMES[r.dayNumber];
  const color = r.isRahu ? "เทาหรือดำ" : DAY_COLORS[r.dayNumber];

  const ranked = r.sums.map((s, c) => ({ s, c })).sort((a, b) => b.s - a.s);
  const best = ranked[0].c;
  const weakest = ranked[ranked.length - 1].c;

  return [
    {
      heading: "ตัวตนของคุณ",
      body: `คนที่เกิดวัน${day}อย่างคุณ ${PERSONALITY[cell(0, 0)].replace(/^คุณ/, "")}`,
      advice: `สีประจำวันเกิดของคุณคือสี${color} ใส่ในวันสำคัญเพื่อเสริมความมั่นใจ`,
    },
    { heading: "การงาน", body: CAREER[cell(2, 2)], advice: ADVICE.career[levelOf(r, [2])] },
    { heading: "การเงิน", body: MONEY[cell(0, 2)], advice: ADVICE.money[levelOf(r, [1, 3])] },
    { heading: "ความรัก", body: LOVE[cell(1, 6)], advice: ADVICE.love[levelOf(r, [6])] },
    { heading: "สุขภาพ", body: HEALTH[cell(2, 0)], advice: ADVICE.health[levelOf(r, [0])] },
    {
      heading: "จุดเด่นและเรื่องที่ต้องใส่ใจ",
      body:
        `ชีวิตคุณได้รับแรงหนุนมากที่สุดในเรื่อง${LIFE_AREAS[best]} เรื่องนี้มักไปได้ดีโดยไม่ต้องออกแรงมาก ` +
        `ส่วนเรื่อง${LIFE_AREAS[weakest]}เป็นเรื่องที่ต้องลงแรงมากกว่าคนอื่นสักหน่อย`,
      advice: `ใช้จุดแข็งเรื่อง${LIFE_AREAS[best]}ช่วยประคองเรื่อง${LIFE_AREAS[weakest]} และให้เวลากับเรื่องนี้อย่างสม่ำเสมอ`,
    },
  ];
}
