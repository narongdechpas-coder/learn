const SUIT_ORDER: Suit[] = ["hearts", "diamonds", "clubs", "spades"];

export const DECK: Card[] = SUIT_ORDER.flatMap((suit, s) =>
  RANKS.map((rank, r) => {
    const [meaning, tone] = MEANINGS[suit][r];
    return { id: s * 13 + r, suit, rank, meaning, tone };
  }),
);

export function cardLabel(card: Card): string {
  return `${card.rank}${SUITS[card.suit].symbol}`;
}
